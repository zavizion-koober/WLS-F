#!/usr/bin/env node
/**
 * Extracts the reason keys the ACTIVE rulepack can emit, from StoneCraft-B's
 * seed, and writes them as a checked-in TypeScript fixture.
 *
 *   node tools/extract-rulepack-keys.mjs [path-to-StoneCraft-B]
 *
 * Why a fixture and not a runtime read: the coverage test has to fail in CI,
 * where the backend repository is not checked out. A test that reads the copy
 * file and asserts it covers itself proves nothing. So the backend's key set is
 * extracted here, committed, and asserted against — and this script is how you
 * refresh it when the rulepack changes.
 *
 * `rulepack-v1.pending.json` is deliberately excluded. It holds the twelve
 * Ascendant rules that were found to be fabricated and are loaded for review but
 * barred from producing output (`RulePendingHumanConfirmation`). They cannot
 * reach a customer, so requiring copy for them would be requiring copy for
 * sentences nobody should ever read.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { homedir } from 'node:os';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const backend = resolve(process.argv[2] ?? join(homedir(), 'Desktop', 'StoneCraft-B'));
const activePack = join(backend, 'seed', 'rulepack-v1.json');

if (!existsSync(activePack)) {
  console.error(`FAIL  no active rulepack at ${activePack}`);
  console.error('      pass the path to StoneCraft-B as the first argument');
  process.exit(1);
}

const keys = [
  ...new Set(
    [...readFileSync(activePack, 'utf8').matchAll(/"reasonKey"\s*:\s*"([^"]+)"/g)].map((m) => m[1]),
  ),
].sort();

const out = `// GENERATED by tools/extract-rulepack-keys.mjs — do not edit by hand.
// Source: StoneCraft-B seed/rulepack-v1.json (the ACTIVE rulepack).
//
// rulepack-v1.pending.json is excluded on purpose: those rules are loaded for
// review and barred from producing output, so they cannot reach a customer.
//
// Refresh with:  node tools/extract-rulepack-keys.mjs <path-to-StoneCraft-B>

/** Every reasonKey the active rulepack can put in a customer response. */
export const RULEPACK_REASON_KEYS: readonly string[] = ${JSON.stringify(keys, null, 2)
  .split('\n')
  .map((line, i) => (i === 0 ? line : `  ${line}`))
  .join('\n')};
`;

const target = join(root, 'src', 'app', 'core', 'content', 'rulepack-reason-keys.ts');
writeFileSync(target, out, 'utf8');
console.log(`ok    ${keys.length} reason keys → src/app/core/content/rulepack-reason-keys.ts`);
